async function insertar() {
  try {
    await mongoose.connect(process.env.MONGO_URI);
    console.log("[Aurea] Conectado a MongoDB");

    let insertados = 0;
    for (const p of productos) {
      const existe = await Product.findOne({ slug: p.slug });
      if (existe) {
        console.log(`⚠ Ya existe: ${p.name}`);
        continue;
      }
      await Product.create({ ...p, publishedAt: new Date() });
      console.log(`✓ Insertado: ${p.name}`);
      insertados++;
    }

    console.log(`\n✅ ${insertados} productos nuevos insertados`);
  } catch (e) {
    console.error("Error:", e.message);
  } finally {
    await mongoose.disconnect();
    console.log("[Aurea] Desconectado");
  }
}

insertar();
